// agenticSDLCShim is the kernel resolution shim placed on each lifecycle
// plugin's bin/ (Claude Code puts a plugin's bin/ on the Bash tool's PATH).
//
// It used to end in "run cadre-install-kernel", which ran bootstrap_sdlc.py,
// which created a venv and pip-installed the kernel. That kernel was Python
// and this repository deleted it (#317); the install kept working only
// because a kernel-v tag is a snapshot, so an installed plugin quietly ran a
// kernel that no longer exists here. The shim fetches the Go kernel from its
// own release instead.
//
// Downloading rather than shipping the binary, unlike the workspace guard.
// The guard fails OPEN, so a failed fetch removes protection silently and
// shipping it was the only safe answer. A missing kernel fails LOUD -- every
// `agentic-sdlc` call errors at the point of use -- so the 23MB per platform
// buys nothing here.
//
// The venv lookup is gone with the bootstrap. An existing venv install falls
// through to the download, which is the migration: the Python kernel stops
// being used without anyone having to uninstall it.
//
// The PATH search deliberately removes this script's own directory first --
// this shim *is* `agentic-sdlc` on the PATH while the plugin is enabled, so a
// plain `command -v agentic-sdlc` finds itself and re-execs forever.
func agenticSDLCShim(kernelVersion string) string {
	return strings.Join([]string{
		"#!/bin/sh",
		"set -eu",
		`BIN_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)`,
		"",
		"# Pinned at generation time, like the CLI shim's CADRE_CLI_VERSION: a",
		"# version resolved at run time would make which kernel you get depend on",
		"# when you ran it.",
		`AGENTIC_SDLC_VERSION="` + kernelVersion + `"`,
		"",
		`if [ -n "${AGENTIC_SDLC_BIN:-}" ]; then`,
		`  exec "$AGENTIC_SDLC_BIN" "$@"`,
		"fi",
		"",
		`CACHE_HOME="${XDG_CACHE_HOME:-$HOME/.cache}"`,
		`CACHE_DIR="$CACHE_HOME/cadre"`,
		`CACHED="$CACHE_DIR/agentic-sdlc-v$AGENTIC_SDLC_VERSION"`,
		"# A cached kernel is re-checked for writability before it is trusted,",
		"# the same gate the workspace guard applies to its own cache: anything",
		"# group- or other-writable is discarded and re-fetched rather than run.",
		`if [ -f "$CACHED" ] && [ -x "$CACHED" ]; then`,
		`  PERMS=$(ls -l "$CACHED" 2>/dev/null | awk '{print $1}')`,
		`  if [ "$(printf '%s' "$PERMS" | cut -c6)" != "w" ] && [ "$(printf '%s' "$PERMS" | cut -c9)" != "w" ]; then`,
		`    exec "$CACHED" "$@"`,
		"  fi",
		`  rm -f "$CACHED"`,
		"fi",
		"",
		"# Strip this shim's own directory from PATH before looking, or `command -v`",
		"# resolves back to this file and loops.",
		`CLEANED_PATH=$(printf '%s' "$PATH" | tr ':' '\n' | grep -vxF "$BIN_DIR" | paste -sd: -)`,
		`FOUND=$(PATH="$CLEANED_PATH" command -v agentic-sdlc 2>/dev/null || true)`,
		`if [ -n "$FOUND" ]; then`,
		`  exec "$FOUND" "$@"`,
		"fi",
		"",
		"# Nothing resolved: fetch the kernel this plugin was generated against.",
		"case \"$(uname -s 2>/dev/null || echo unknown)\" in",
		"  Linux)  GOOS=linux ;;",
		"  Darwin) GOOS=darwin ;;",
		"  MINGW*|MSYS*|CYGWIN*) GOOS=windows ;;",
		`  *) echo "agentic-sdlc: no kernel for this platform" >&2; exit 1 ;;`,
		"esac",
		"case \"$(uname -m 2>/dev/null || echo unknown)\" in",
		"  x86_64|amd64)  GOARCH=amd64 ;;",
		"  aarch64|arm64) GOARCH=arm64 ;;",
		`  *) echo "agentic-sdlc: no kernel for this architecture" >&2; exit 1 ;;`,
		"esac",
		"",
		`if [ "$GOOS" = "windows" ]; then`,
		`  ARCHIVE="agentic-sdlc-v$AGENTIC_SDLC_VERSION-$GOOS-$GOARCH.zip"`,
		`  MEMBER="agentic-sdlc.exe"`,
		"else",
		`  ARCHIVE="agentic-sdlc-v$AGENTIC_SDLC_VERSION-$GOOS-$GOARCH.tar.gz"`,
		`  MEMBER="agentic-sdlc"`,
		"fi",
		`BASE="https://github.com/deagy/cadre/releases/download/kernel-v$AGENTIC_SDLC_VERSION"`,
		"",
		`TEMP_DIR=$(mktemp -d) || exit 1`,
		`trap 'rm -rf "$TEMP_DIR"' EXIT`,
		"",
		"fetch() {",
		"  if command -v curl >/dev/null 2>&1; then",
		`    curl -fsSL --connect-timeout 5 --max-time 60 --proto '=https' -o "$2" "$1"`,
		"  elif command -v wget >/dev/null 2>&1; then",
		`    wget -q --timeout=5 -O "$2" "$1"`,
		"  else",
		"    return 1",
		"  fi",
		"}",
		"",
		`if ! fetch "$BASE/$ARCHIVE" "$TEMP_DIR/$ARCHIVE" || ! fetch "$BASE/SHA256SUMS" "$TEMP_DIR/SHA256SUMS"; then`,
		`  echo "agentic-sdlc: could not download the lifecycle kernel (v$AGENTIC_SDLC_VERSION). Set AGENTIC_SDLC_BIN to a kernel you already have, or install one on PATH." >&2`,
		"  exit 1",
		"fi",
		"",
		"# Verify before trusting. An unverified kernel decides gate approvals.",
		`EXPECTED=$(grep " $ARCHIVE\$" "$TEMP_DIR/SHA256SUMS" 2>/dev/null | awk '{print $1}')`,
		`if [ -z "$EXPECTED" ]; then`,
		`  echo "agentic-sdlc: $ARCHIVE is not listed in the release's SHA256SUMS" >&2`,
		"  exit 1",
		"fi",
		"if command -v sha256sum >/dev/null 2>&1; then",
		`  ACTUAL=$(sha256sum "$TEMP_DIR/$ARCHIVE" | awk '{print $1}')`,
		"elif command -v shasum >/dev/null 2>&1; then",
		`  ACTUAL=$(shasum -a 256 "$TEMP_DIR/$ARCHIVE" | awk '{print $1}')`,
		"else",
		`  echo "agentic-sdlc: no sha256 tool available to verify the download" >&2`,
		"  exit 1",
		"fi",
		`if [ "$ACTUAL" != "$EXPECTED" ]; then`,
		`  echo "agentic-sdlc: checksum mismatch on $ARCHIVE" >&2`,
		"  exit 1",
		"fi",
		"",
		`if [ "$GOOS" = "windows" ]; then`,
		`  unzip -q -o -j "$TEMP_DIR/$ARCHIVE" "$MEMBER" -d "$TEMP_DIR" || exit 1`,
		"else",
		`  tar -xzf "$TEMP_DIR/$ARCHIVE" -C "$TEMP_DIR" "$MEMBER" || exit 1`,
		"fi",
		"",
		`mkdir -p "$CACHE_DIR"`,
		`chmod 700 "$TEMP_DIR/$MEMBER"`,
		`mv "$TEMP_DIR/$MEMBER" "$CACHED"`,
		`exec "$CACHED" "$@"`,
		"",
	}, "\n")
}

// binaryShimFunctions embeds shell functions to resolve (locate or download)
// the compiled Go binary, separate from execution. Resolution suppresses noise;
// execution preserves all CLI output and exit codes. On resolution failure,
// BINARY_CACHE is set to empty, signaling fallback to Python.
var binaryShimFunctions = strings.Join([]string{
	"# Resolve a cached Go binary for the current platform, downloading if necessary.",
	"# Sets BINARY_CACHE to the path on success, or empty on failure.",
	"# All download noise is suppressed; return code signals success/failure only.",
	"try_resolve_binary() {",
	"  CACHE_DIR=\"${XDG_CACHE_HOME:-$HOME/.cache}/cadre\"",
	"  BINARY_CACHE=\"\"",
	"  ",
	"  # Determine platform from uname output.",
	"  case \"$(uname -s)\" in",
	"    Linux)  GOOS=linux ;;",
	"    Darwin) GOOS=darwin ;;",
	// This POSIX sh shim only ever runs on Windows under Git Bash, MSYS2 or
	// Cygwin, which is exactly what these uname strings identify
	// (MINGW64_NT-10.0-19045, MSYS_NT-10.0-19045, CYGWIN_NT-10.0). Without
	// them the windows/zip/cadre.exe branch below was unreachable, so the
	// windows-amd64 binary the release pipeline builds and publishes could
	// never be used by a plugin install.
	"    MINGW*|MSYS*|CYGWIN*) GOOS=windows ;;",
	"    *)      return 1 ;;  # Unsupported platform",
	"  esac",
	"  ",
	"  case \"$(uname -m)\" in",
	"    x86_64|amd64) GOARCH=amd64 ;;",
	"    aarch64|arm64) GOARCH=arm64 ;;",
	"    *)      return 1 ;;  # Unsupported architecture",
	"  esac",
	"  ",
	"  # No darwin/amd64 release. The CLI links sqlite and so needs cgo and a",
	"  # native host per platform; GitHub retired the free Intel macOS runner.",
	"  # Rosetta cannot help -- it translates x86_64 for Apple Silicon, not the",
	"  # reverse -- so this is a build-from-source platform. Said here rather",
	"  # than left to a 404 on an asset name.",
	"  if [ \"$GOOS\" = \"darwin\" ] && [ \"$GOARCH\" = \"amd64\" ]; then",
	`    echo "cadre: no release binary for Intel macOS (darwin/amd64)." >&2`,
	`    echo "  Apple Silicon is served by darwin/arm64; Rosetta does not run it on Intel." >&2`,
	`    echo "  Build from source: go build -o cadre ./cmd/cadre  (needs Go and cgo)" >&2`,
	`    echo "  Or set CADRE_BINARY to a cadre binary you already have." >&2`,
	"    return 1",
	"  fi",
	"  ",
	"  # Try to use a cached binary if it exists, is a regular file, and is executable.",
	"  CANDIDATE=\"$CACHE_DIR/cadre-v$CADRE_CLI_VERSION-$GOOS-$GOARCH\"",
	"  if [ -f \"$CANDIDATE\" ] && [ -x \"$CANDIDATE\" ]; then",
	"    # Verify the cached binary's sidecar hash, ownership, and permissions (offline, no network).",
	"    if verify_cached_binary \"$CANDIDATE\"; then",
	"      BINARY_CACHE=\"$CANDIDATE\"",
	"      return 0",
	"    fi",
	"    # Sidecar hash mismatch, ownership/permission violation, or missing sidecar:",
	"    # discard the cached binary and re-download it.",
	"    rm -f \"$CANDIDATE\" \"${CANDIDATE}.sha256\"",
	"  fi",
	"  ",
	"  # Cached binary not available or verification failed; try to download, verify, and cache it.",
	"  download_binary \"$GOOS\" \"$GOARCH\" \"$CANDIDATE\" \"$CADRE_CLI_VERSION\" || return 1",
	"  BINARY_CACHE=\"$CANDIDATE\"",
	"  return 0",
	"}",
	"",
	"# Verify a cached binary's sidecar hash and ownership.",
	"# Detects corruption, partial writes, and unprivileged tampering (offline, no network).",
	"# A process with user's UID is outside what cache-local controls can defend.",
	"# Returns 0 if valid, 1 if missing/mismatched/untrusted.",
	"verify_cached_binary() {",
	"  BINARY_PATH=\"$1\"",
	"  ",
	"  # Check that the cached binary still exists and is a regular file.",
	"  [ -f \"$BINARY_PATH\" ] || return 1",
	"  ",
	"  # Check ownership: binary must be owned by current user.",
	"  CURRENT_UID=$(id -u) || return 1",
	"  BINARY_UID=$(ls -n \"$BINARY_PATH\" 2>/dev/null | awk '{print $3}') || return 1",
	"  [ \"$CURRENT_UID\" = \"$BINARY_UID\" ] || return 1",
	"  ",
	"  # Check permissions: binary must not be writable by group (position 6) or others (position 9).",
	"  PERMS=$(ls -l \"$BINARY_PATH\" 2>/dev/null | awk '{print $1}') || return 1",
	"  # Extract group write bit (character 6) and other write bit (character 9)",
	"  GROUP_WRITE=$(echo \"$PERMS\" | cut -c6)",
	"  OTHER_WRITE=$(echo \"$PERMS\" | cut -c9)",
	"  [ \"$GROUP_WRITE\" != \"w\" ] || return 1",
	"  [ \"$OTHER_WRITE\" != \"w\" ] || return 1",
	"  ",
	"  # Check sidecar hash: read expected hash from .sha256 file (computed at cache time).",
	"  SIDECAR_PATH=\"${BINARY_PATH}.sha256\"",
	"  [ -f \"$SIDECAR_PATH\" ] || return 1",
	"  EXPECTED_HASH=$(cat \"$SIDECAR_PATH\" 2>/dev/null) || return 1",
	"  [ -n \"$EXPECTED_HASH\" ] || return 1",
	"  ",
	"  # Compute actual hash of binary and compare.",
	"  if command -v sha256sum >/dev/null 2>&1; then",
	"    ACTUAL_HASH=$(sha256sum \"$BINARY_PATH\" 2>/dev/null | awk '{print $1}')",
	"  elif command -v shasum >/dev/null 2>&1; then",
	"    ACTUAL_HASH=$(shasum -a 256 \"$BINARY_PATH\" 2>/dev/null | awk '{print $1}')",
	"  else",
	"    return 1",
	"  fi",
	"  ",
	"  [ \"$ACTUAL_HASH\" = \"$EXPECTED_HASH\" ]",
	"}",
	"",
	"# Download a release binary from GitHub, verify its checksum, and cache it.",
	"# All output is suppressed to avoid download noise.",
	"download_binary() {",
	"  GOOS=\"$1\"",
	"  GOARCH=\"$2\"",
	"  BINARY_CACHE=\"$3\"",
	"  VERSION=\"$4\"",
	"  ",
	"  # Determine archive extension based on OS.",
	"  if [ \"$GOOS\" = \"windows\" ]; then",
	"    ARCHIVE_EXT=\"zip\"",
	"    EXECUTABLE=\"cadre.exe\"",
	"  else",
	"    ARCHIVE_EXT=\"tar.gz\"",
	"    EXECUTABLE=\"cadre\"",
	"  fi",
	"  ",
	"  # Download from GitHub releases using cli-v<version> tag (not plugin-v).",
	"  ARCHIVE_NAME=\"cadre-v$VERSION-$GOOS-$GOARCH.$ARCHIVE_EXT\"",
	"  RELEASE_URL=\"https://github.com/deagy/cadre/releases/download/cli-v$VERSION/$ARCHIVE_NAME\"",
	"  SHA256SUMS_URL=\"https://github.com/deagy/cadre/releases/download/cli-v$VERSION/SHA256SUMS\"",
	"  ",
	"  # Download into a temporary location first, then verify and move.",
	"  TEMP_DIR=$(mktemp -d) || return 1",
	"  trap \"rm -rf \\\"$TEMP_DIR\\\"\" EXIT",
	"  ",
	"  ARCHIVE_PATH=\"$TEMP_DIR/$ARCHIVE_NAME\"",
	"  ",
	"  # Try to download the archive. Use curl if available, fall back to wget.",
	"  if command -v curl >/dev/null 2>&1; then",
	"    curl -fsSL --connect-timeout 5 --max-time 10 --proto '=https' -o \"$ARCHIVE_PATH\" \"$RELEASE_URL\" 2>/dev/null || return 1",
	"  elif command -v wget >/dev/null 2>&1; then",
	"    wget -q --timeout=5 -O \"$ARCHIVE_PATH\" \"$RELEASE_URL\" 2>/dev/null || return 1",
	"  else",
	"    return 1",
	"  fi",
	"  ",
	"  # Download SHA256SUMS file for verification.",
	"  SHA256SUMS_PATH=\"$TEMP_DIR/SHA256SUMS\"",
	"  if command -v curl >/dev/null 2>&1; then",
	"    curl -fsSL --connect-timeout 5 --max-time 10 --proto '=https' -o \"$SHA256SUMS_PATH\" \"$SHA256SUMS_URL\" 2>/dev/null || return 1",
	"  elif command -v wget >/dev/null 2>&1; then",
	"    wget -q --timeout=5 -O \"$SHA256SUMS_PATH\" \"$SHA256SUMS_URL\" 2>/dev/null || return 1",
	"  else",
	"    return 1",
	"  fi",
	"  ",
	"  # Verify the checksum.",
	"  EXPECTED_HASH=$(grep \"$ARCHIVE_NAME\" \"$SHA256SUMS_PATH\" 2>/dev/null | awk '{print $1}') || return 1",
	"  if [ -z \"$EXPECTED_HASH\" ]; then",
	"    return 1",
	"  fi",
	"  ",
	"  # Compute the actual hash of the downloaded archive.",
	"  if command -v sha256sum >/dev/null 2>&1; then",
	"    ACTUAL_HASH=$(sha256sum \"$ARCHIVE_PATH\" | awk '{print $1}')",
	"  elif command -v shasum >/dev/null 2>&1; then",
	"    ACTUAL_HASH=$(shasum -a 256 \"$ARCHIVE_PATH\" | awk '{print $1}')",
	"  else",
	"    return 1",
	"  fi",
	"  ",
	"  # Checksum mismatch is a failure condition.",
	"  if [ \"$ACTUAL_HASH\" != \"$EXPECTED_HASH\" ]; then",
	"    return 1",
	"  fi",
	"  ",
	"  # Extract ONLY the named executable from the archive (defense-in-depth).",
	"  # This restricts extraction to the binary we expect, ignoring other archive contents.",
	"  if [ \"$ARCHIVE_EXT\" = \"zip\" ]; then",
	"    unzip -q -o \"$ARCHIVE_PATH\" \"$EXECUTABLE\" -d \"$TEMP_DIR\" 2>/dev/null || return 1",
	"  else",
	"    tar -xzf \"$ARCHIVE_PATH\" -C \"$TEMP_DIR\" \"$EXECUTABLE\" 2>/dev/null || return 1",
	"  fi",
	"  ",
	"  EXTRACTED_BINARY=\"$TEMP_DIR/$EXECUTABLE\"",
	"  # Verify the extracted binary is a regular file, not a symlink or directory.",
	"  if [ ! -f \"$EXTRACTED_BINARY\" ] || [ -L \"$EXTRACTED_BINARY\" ]; then",
	"    return 1",
	"  fi",
	"  ",
	"  if [ ! -x \"$EXTRACTED_BINARY\" ]; then",
	"    return 1",
	"  fi",
	"  ",
	"  # Opportunistically verify the build provenance (if gh CLI is available).",
	"  # This is a defense-in-depth check; it is not required to succeed.",
	"  if command -v gh >/dev/null 2>&1; then",
	"    # Try to verify the attestation for the archive we downloaded.",
	"    ATTEST_OUT=$(gh attestation verify \"$ARCHIVE_PATH\" --repo deagy/cadre 2>&1)",
	"    if [ $? -ne 0 ] && [ -n \"$ATTEST_OUT\" ]; then",
	"      # Attestation verification failed (not missing gh): emit non-blocking note.",
	"      echo \"cadre: attestation verification failed (non-blocking)\" >&2",
	"    fi",
	"  fi",
	"  ",
	"  # Create the cache directory with restrictive permissions (mode 700).",
	"  # Use install unconditionally to enforce perms (existing 0755 dirs get tightened).",
	"  install -m 700 -d \"$CACHE_DIR\" 2>/dev/null || return 1",
	"  ",
	"  # Atomically move the binary to the cache.",
	"  BINARY_TEMP=\"$CACHE_DIR/cadre-v$VERSION-$GOOS-$GOARCH.tmp.$$\"",
	"  cp \"$EXTRACTED_BINARY\" \"$BINARY_TEMP\" || return 1",
	"  chmod +x \"$BINARY_TEMP\" || return 1",
	"  ",
	"  # H2: Reject pre-existing directory at target path (mv would move file into it).",
	"  # Clean up BINARY_TEMP on the way out: it is created and chmod +x'd above,",
	"  # so returning here without removing it leaves an executable .tmp.$$ behind",
	"  # in the cache on every collision.",
	"  if [ -d \"$BINARY_CACHE\" ]; then",
	"    rm -f \"$BINARY_TEMP\"",
	"    return 1",
	"  fi",
	"  ",
	"  if ! mv \"$BINARY_TEMP\" \"$BINARY_CACHE\" 2>/dev/null; then",
	"    rm -f \"$BINARY_TEMP\"",
	"    return 1",
	"  fi",
	"  ",
	"  # Save the binary's hash to a sidecar file for offline verification.",
	"  # On the warm path, verify_cached_binary will check this hash without network.",
	"  if command -v sha256sum >/dev/null 2>&1; then",
	"    sha256sum \"$BINARY_CACHE\" 2>/dev/null | awk '{print $1}' > \"${BINARY_CACHE}.sha256\" || true",
	"  elif command -v shasum >/dev/null 2>&1; then",
	"    shasum -a 256 \"$BINARY_CACHE\" 2>/dev/null | awk '{print $1}' > \"${BINARY_CACHE}.sha256\" || true",
	"  fi",
	"  ",
	"  return 0",
	"}",
	"",
}, "\n")

