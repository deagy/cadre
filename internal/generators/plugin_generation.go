// resetGeneratedContent removes exactly the generated set before regenerating.
// Derived from generatedTopLevel rather than re-listed, so a new member can
// never be generated-but-not-reset (which would leave stale files that
// filesEqual then reports as drift forever, with no way to regenerate out of
// it). bin/ is the one entry not removed wholesale: only bin/cadre is
// generated, and the directory may legitimately hold nothing else. README.md
// is the one entry that may need to survive too, when removeReadme is false.
func resetGeneratedContent(pluginRoot string, removeReadme bool) error {
	names := make([]string, 0, len(generatedTopLevel))
	for name := range generatedTopLevel {
		if name == "bin" {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if name == "README.md" && !removeReadme {
			continue
		}
		if err := os.RemoveAll(filepath.Join(pluginRoot, name)); err != nil {
			return err
		}
	}
	if err := os.RemoveAll(filepath.Join(pluginRoot, "bin", "cadre")); err != nil {
		return err
	}
	// Nested generated content: reset only the generated subtree itself, never
	// its hand-authored siblings -- e.g. plugins/lifecycle/skills/ is removed
	// and regenerated, but plugins/lifecycle/.claude-plugin/, .codex-plugin/,
	// and tools/ (the plugin's own manifests and bootstrap tooling) survive.
	for _, relative := range generatedNestedPaths {
		if err := os.RemoveAll(filepath.Join(pluginRoot, filepath.FromSlash(relative))); err != nil {
			return err
		}
	}
	return nil
}

