// isKernelDoc reports whether a docs/ path documents the lifecycle kernel
// rather than the role suite. Those documents describe G1-G10 gate semantics
// and the LangGraph engine -- neither of which the packaged role suite
// contains -- and their relative links point at kernel/ and engine/ siblings
// the package does not ship, so copying them in produces a plugin full of
// dangling links.
func isKernelDoc(relative string) bool {
	for _, part := range strings.Split(relative, "/") {
		if part == "kernel" {
			return true
		}
	}
	return false
}

