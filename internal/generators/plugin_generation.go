func writeFile(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("cannot create directory %s: %w", filepath.Dir(path), err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		return fmt.Errorf("cannot write %s: %w", path, err)
	}
	return nil
}

// copyFile mirrors shutil.copy2: contents plus the source's permission bits.
func copyFile(source, target string) error {
	info, err := os.Stat(source)
	if err != nil {
		return err
	}
	content, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(target, content, info.Mode().Perm()); err != nil {
		return err
	}
	return os.Chmod(target, info.Mode().Perm())
}

// copyTree copies a directory verbatim, refusing symlinks rather than
// dereferencing them (which would silently vendor out-of-tree content into a
// published package).
func copyTree(source, target string) ([]string, error) {
	var copied []string
	err := filepath.WalkDir(source, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, relErr := filepath.Rel(source, p)
		if relErr != nil {
			return relErr
		}
		destination := filepath.Join(target, rel)
		info, lstatErr := os.Lstat(p)
		if lstatErr != nil {
			return lstatErr
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("%s: symlinks are not packaged; replace it with a regular file", p)
		}
		if d.IsDir() {
			return os.MkdirAll(destination, 0o755)
		}
		if err := copyFile(p, destination); err != nil {
			return err
		}
		copied = append(copied, destination)
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(copied)
	return copied, nil
}

func listFiles(root string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			out = append(out, p)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(out)
	return out, nil
}

// relSlash returns the slash-separated relative path from base to target.
func relSlash(base, target string) (string, error) {
	rel, err := filepath.Rel(base, target)
	if err != nil {
		return "", err
	}
	return filepath.ToSlash(rel), nil
}

// gitTrackedFiles returns the repository-relative paths git tracks under
// pathspec, filtered to those that currently exist as regular files -- the
// same `git ls-files` + is_file() pair the Python generator uses.
func gitTrackedFiles(repoRoot, pathspec string) ([]string, error) {
	command := exec.Command("git", "ls-files", pathspec)
	command.Dir = repoRoot
	output, err := command.Output()
	if err != nil {
		return nil, fmt.Errorf("git ls-files %s failed: %w", pathspec, err)
	}
	var out []string
	for _, line := range pySplitLines(string(output)) {
		if line == "" {
			continue
		}
		if info, err := os.Stat(filepath.Join(repoRoot, filepath.FromSlash(line))); err != nil || info.IsDir() {
			continue
		}
		out = append(out, line)
	}
	sort.Strings(out)
	return out, nil
}

// sdlcShellDispatch is the packaged wrapper's `sdlc` branch.
//
// It stays a special case because `cadre sdlc` shells out to a *separately
// installed* kernel binary and must pass the plugin's own provider.json --
// a path only the wrapper knows, since the binary is resolved from a cache
// directory elsewhere.
//
// AGENTIC_SDLC_BIN is the settings resolver's highest-precedence source, so
// honoring it directly here cannot get the precedence order wrong. Anything
// below it goes through `cadre config resolve`, which is the same chain
// settings.py implemented -- the wrapper no longer needs Python for this.
func (g *pluginGenerator) sdlcShellDispatch() []string {
	return []string{
		`if [ "$command_name" = "sdlc" ]; then`,
		`  sdlc_bin="${AGENTIC_SDLC_BIN:-}"`,
		`  if [ -z "$sdlc_bin" ]; then`,
		`    sdlc_bin=$(CADRE_REPO_ROOT="$SUITE_ROOT" "$BINARY_CACHE" config resolve agentic_sdlc.bin_path) || exit 1`,
		"  fi",
		fmt.Sprintf(`  [ -n "$sdlc_bin" ] || { echo "cadre: install Agentic SDLC %s from https://github.com/deagy/cadre" >&2; exit 1; }`,
			g.kernelRequirementText()),
		`  exec "$sdlc_bin" --provider "$PLUGIN_ROOT/provider.json" "$@"`,
		"fi",
	}
}
