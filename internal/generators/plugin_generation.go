// capabilityProfile is one entry of runner-capabilities.json's capability_tiers.
type capabilityProfile struct {
	Tools       []string `json:"tools"`
	SandboxMode string   `json:"sandbox_mode"`
}

// runnerCapabilities is the single source of truth for capability tiers, model
// tiers, and the reasoning efforts both runners accept. Every derived constant
// is read from the file rather than hand-duplicated, so drift between this
// package and the manifest is structurally impossible.
type runnerCapabilities struct {
	CapabilityTiers         map[string]capabilityProfile `json:"capability_tiers"`
	ModelTiers              map[string]ModelTierInfo     `json:"model_tiers"`
	AllowedReasoningEfforts []string                     `json:"allowed_reasoning_efforts"`
}

// writeCapableTiers is every capability tier whose sandbox_mode is not
// "read-only" -- i.e. every tier that can make a repository edit. Derived from
// the manifest rather than hardcoded tier names.
func (r *runnerCapabilities) writeCapableTiers() map[string]bool {
	out := map[string]bool{}
	for name, profile := range r.CapabilityTiers {
		if profile.SandboxMode != "read-only" {
			out[name] = true
		}
	}
	return out
}

// pluginGenerator holds the resolved input roots for one generation run.
