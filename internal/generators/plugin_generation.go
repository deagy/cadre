func (g *pluginGenerator) generateSkillCopies(pluginRoot string) ([]string, error) {
	tracked, err := gitTrackedFiles(g.repoRoot, ".agents/skills")
	if err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(g.skillsRoot)
	if err != nil {
		return nil, fmt.Errorf("cannot read %s: %w", g.skillsRoot, err)
	}
	var skillNames []string
	for _, entry := range entries {
		if entry.IsDir() {
			skillNames = append(skillNames, entry.Name())
		}
	}
	sort.Strings(skillNames)

	var written []string
	for _, name := range skillNames {
		skillDir := filepath.Join(g.skillsRoot, name)
		if info, err := os.Stat(filepath.Join(skillDir, "SKILL.md")); err != nil || info.IsDir() {
			continue
		}
		packageRoot := "skills"
		if override, ok := skillPackageTargets[name]; ok {
			packageRoot = override
		}
		targetDir := filepath.Join(pluginRoot, filepath.FromSlash(packageRoot), name)

		prefix := ".agents/skills/" + name + "/"
		var members []string
		for _, relative := range tracked {
			if strings.HasPrefix(relative, prefix) {
				members = append(members, relative)
			}
		}
		sort.Strings(members)
		for _, relative := range members {
			source := filepath.Join(g.repoRoot, filepath.FromSlash(relative))
			if info, err := os.Lstat(source); err == nil && info.Mode()&os.ModeSymlink != 0 {
				return nil, fmt.Errorf("symlinks are not allowed in packaged skills: %s", relative)
			}
			target := filepath.Join(targetDir, filepath.FromSlash(strings.TrimPrefix(relative, prefix)))
			if err := copyFile(source, target); err != nil {
				return nil, err
			}
		}

		// target_dir sits packageRoot's depth + 1 (the skill's own directory)
		// below pluginRoot -- "skills/<name>/" is 2 levels down,
		// "plugins/lifecycle/skills/<name>/" is 4. Computed rather than
		// hardcoded so a skillPackageTargets entry can never ship a wrong hint.
		upLevels := strings.Repeat("../", len(strings.Split(packageRoot, "/"))+1)
		upLevels = strings.TrimSuffix(upLevels, "/")
		packageNote := "\n\n> Packaged suite note: when the current project has no local `roster/` " +
			"tree, resolve suite files under `" + upLevels + "/suite/roster/` relative to this " +
			"`SKILL.md`. The packaged plugin is self-contained; do not look for the " +
			"source checkout.\n"

		skillTarget := filepath.Join(targetDir, "SKILL.md")
		raw, err := os.ReadFile(skillTarget)
		if err != nil {
			return nil, fmt.Errorf("cannot read packaged skill %s: %w", skillTarget, err)
		}
		content := string(raw)
		// Deliberately the same raw substring search the Python does
		// (content.find("---", 3) + 3), not the exact-line frontmatter helper:
		// SKILL.md frontmatter is written by hand and the two have never
		// disagreed, and changing it here would silently move the note.
		offset := strings.Index(content[3:], "---")
		if offset < 0 {
			return nil, fmt.Errorf("%s: no closing frontmatter delimiter", skillTarget)
		}
		frontmatterEnd := offset + 3 + 3
		if err := writeFile(skillTarget, content[:frontmatterEnd]+packageNote+content[frontmatterEnd:]); err != nil {
			return nil, err
		}

		files, err := listFiles(targetDir)
		if err != nil {
			return nil, err
		}
		written = append(written, files...)
	}
	return written, nil
}

