type subcommandRow struct {
	name        string
	script      string
	description string
}

func loadSubcommandTable(repoRoot string) ([]subcommandRow, error) {
	raw, err := os.ReadFile(filepath.Join(repoRoot, "bin", "subcommands.tsv"))
	if err != nil {
		return nil, err
	}
	var rows []subcommandRow
	for _, line := range pySplitLines(string(raw)) {
		if line == "" {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 3 {
			return nil, fmt.Errorf("bin/subcommands.tsv: expected 3 tab-separated columns, got %d: %q",
				len(fields), line)
		}
		rows = append(rows, subcommandRow{fields[0], fields[1], fields[2]})
	}
	return rows, nil
}

// packagedSubcommands is the single derivation point for which
// bin/subcommands.tsv entries ship in the packaged plugin's own bin/cadre and
// which script path each maps to, so a script rename or a new subcommand only
// needs to change bin/subcommands.tsv -- not this generator's shell text too.
func packagedSubcommands(repoRoot string) ([]subcommandRow, error) {
	rows, err := loadSubcommandTable(repoRoot)
	if err != nil {
		return nil, err
	}
	var out []subcommandRow
	for _, row := range rows {
		if packagedSubcommandExclusions[row.name] {
			continue
		}
		out = append(out, row)
	}
	return out, nil
}

func (g *pluginGenerator) providerManifest() (*orderedJSON, error) {
	raw, err := os.ReadFile(filepath.Join(g.providerRoot, "provider.json"))
	if err != nil {
		return nil, fmt.Errorf("cannot read provider.json: %w", err)
	}
	return parseOrderedJSON(raw)
}

// kernelRequirementText interpolates the declared kernel range into the
// generated launcher. The launcher is POSIX sh with no JSON parser, so it
// cannot read provider.json at runtime; resolve it here instead. Do not
// hardcode a version -- provider.json's own `version` and its
// `kernel_compatibility` are different version lines.
func (g *pluginGenerator) kernelRequirementText() string {
	manifest, err := g.providerManifest()
	if err != nil {
		return "a compatible version"
	}
	compatibilityAny, ok := manifest.Get("kernel_compatibility")
	if !ok {
		return "a compatible version"
	}
	compatibility, ok := compatibilityAny.(*orderedJSON)
	if !ok {
		return "a compatible version"
	}
	minimumAny, ok := compatibility.Get("minimum")
	if !ok {
		return "a compatible version"
	}
	minimum, ok := minimumAny.(string)
	if !ok {
		return "a compatible version"
	}
	return "v" + minimum + "+"
}

func (g *pluginGenerator) generateBinWrapper(pluginRoot string) (string, error) {
	rows, err := packagedSubcommands(g.repoRoot)
	if err != nil {
		return "", err
	}
	caseLines := make([]string, 0, len(rows))
	names := make([]string, 0, len(rows)+1)
	for _, row := range rows {
		extra := ""
		if value, ok := packagedSubcommandExtraArgs[row.name]; ok {
			extra = value + " "
		}
		caseLines = append(caseLines, fmt.Sprintf(
			`  %s) exec "$AGENT_PYTHON" "$SUITE_ROOT/%s" %s"$@" ;;`, row.name, row.script, extra))
		names = append(names, row.name)
	}
	names = append(names, "sdlc")
	usage := strings.Join(names, "|")

	body := []string{
		"#!/bin/sh",
		"set -eu",
		`BIN_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)`,
		`PLUGIN_ROOT=$(CDPATH= cd -- "$BIN_DIR/.." && pwd)`,
		`SUITE_ROOT="$PLUGIN_ROOT/suite"`,
		`if [ "${1:-}" = "--interactive" ]; then`,
		"  CADRE_INTERACTIVE=1",
		"  export CADRE_INTERACTIVE",
		"  shift",
		"fi",
		`command_name="${1:-help}"`,
		`[ "$#" -gt 0 ] && shift || true`,
		// Release automation updates the hand-authored plugin manifests without
		// regenerating this wrapper. Read its package-local manifest at
		// invocation time, rather than baking a copy of that
		// independently-versioned value into generated content.
		`if [ "$command_name" = "--version" ] && [ "$#" -eq 0 ]; then`,
		`  plugin_version=$(sed -n 's/^[[:space:]]*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$PLUGIN_ROOT/.claude-plugin/plugin.json")`,
		`  [ -n "$plugin_version" ] || { echo "cadre: could not read plugin version from .claude-plugin/plugin.json" >&2; exit 1; }`,
		`  printf 'cadre %s\n' "$plugin_version"`,
		`  exit 0`,
		`fi`,
		"detect_agent_python() {",
		"  AGENT_PYTHON=",
		"  for candidate in python3 python; do",
		`    command -v "$candidate" >/dev/null 2>&1 || continue`,
		"    if \"$candidate\" -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 10) else 1)' 2>/dev/null; then AGENT_PYTHON=\"$candidate\"; break; fi",
		"  done",
		"}",
		`if [ "$command_name" = "sdlc" ]; then`,
		// AGENTIC_SDLC_BIN is settings.py's *highest*-precedence source for this
		// field, so honoring it directly here needs no Python and cannot get the
		// precedence order wrong. Everything below that MUST go through
		// settings.py's resolve_optional() so the config file is actually
		// consulted and wins over a same-named binary that merely happens to be
		// on PATH.
		`  sdlc_bin="${AGENTIC_SDLC_BIN:-}"`,
		`  if [ -z "$sdlc_bin" ]; then`,
		"    detect_agent_python",
		`    if [ -n "$AGENT_PYTHON" ]; then`,
		`      sdlc_bin=$("$AGENT_PYTHON" "$SUITE_ROOT/roster/shared/src/settings.py" resolve agentic_sdlc.bin_path) || exit 1`,
		"    else",
		`      echo "cadre: no Python 3.10+ found; falling back to PATH for agentic-sdlc without reading any cadre config file (a configured agentic_sdlc.bin_path, if set, is being ignored)" >&2`,
		`      sdlc_bin=$(command -v agentic-sdlc || true)`,
		"    fi",
		"  fi",
		fmt.Sprintf(`  [ -n "$sdlc_bin" ] || { echo "cadre: install Agentic SDLC %s from https://github.com/deagy/cadre" >&2; exit 1; }`,
			g.kernelRequirementText()),
		`  exec "$sdlc_bin" --provider "$PLUGIN_ROOT/provider.json" "$@"`,
		"fi",
		"detect_agent_python",
		`[ -n "$AGENT_PYTHON" ] || { echo "cadre: Python 3.10+ is required" >&2; exit 1; }`,
		`case "$command_name" in`,
	}
	body = append(body, caseLines...)
	body = append(body,
		fmt.Sprintf(`  help|-h|--help) echo "Usage: cadre [--interactive] {%s} [args...]" ;;`, usage),
		`  *) echo "cadre: unknown subcommand $command_name" >&2; exit 1 ;;`,
		"esac",
		"",
	)

	target := filepath.Join(pluginRoot, "bin", "cadre")
	if err := writeFile(target, strings.Join(body, "\n")); err != nil {
		return "", err
	}
	if err := os.Chmod(target, 0o755); err != nil { //nolint:gosec // intentionally executable
		return "", err
	}
	return target, nil
}

