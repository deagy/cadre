// generateKernelCompatibility ships the kernel compatibility window, the
// bootstrap script, the SessionStart hook, the install skill, and the two bin
// shims into each lifecycle plugin.
//
// The window is derived from provider.json rather than copied wholesale: the
// bootstrap only needs {minimum, maximum_exclusive}, and provider.json also
// carries an unrelated `version` field that has been mistaken for the kernel
// range before.
func (g *pluginGenerator) generateKernelCompatibility(pluginRoot string) ([]string, error) {
	manifest, err := g.providerManifest()
	if err != nil {
		return nil, err
	}
	compatibilityAny, ok := manifest.Get("kernel_compatibility")
	if !ok {
		return nil, fmt.Errorf("provider.json: missing kernel_compatibility")
	}
	compatibility, ok := compatibilityAny.(*orderedJSON)
	if !ok {
		return nil, fmt.Errorf("provider.json: kernel_compatibility is not an object")
	}
	minimum, _ := compatibility.Get("minimum")
	maximum, _ := compatibility.Get("maximum_exclusive")
	payload := newOrderedJSON().
		Set("_comment", "Generated from provider.json's kernel_compatibility by "+
			"cadre generate-plugin. Do not hand-edit; edit provider/provider.json "+
			"and regenerate.").
		Set("minimum", minimum).
		Set("maximum_exclusive", maximum)
	payloadText := pyJSONDumps(payload, 0) + "\n"

	var written []string
	for _, relative := range kernelCompatibilityTargets {
		target := filepath.Join(pluginRoot, filepath.FromSlash(relative))
		if err := writeFile(target, payloadText); err != nil {
			return nil, err
		}
		written = append(written, target)
	}

	bootstrap, err := os.ReadFile(g.bootstrapSource)
	if err != nil {
		return nil, fmt.Errorf("cannot read %s: %w", g.bootstrapSource, err)
	}
	for _, relative := range bootstrapTargets {
		target := filepath.Join(pluginRoot, filepath.FromSlash(relative))
		if err := writeFile(target, string(bootstrap)); err != nil {
			return nil, err
		}
		written = append(written, target)
	}

	hooksJSON := pyJSONDumps(lifecycleHooks(), 0) + "\n"
	for _, relative := range lifecycleHookTargets {
		target := filepath.Join(pluginRoot, filepath.FromSlash(relative))
		if err := writeFile(target, hooksJSON); err != nil {
			return nil, err
		}
		written = append(written, target)
	}

	installSkill, err := os.ReadFile(filepath.Join(g.skillsRoot, "cadre-install-kernel", "SKILL.md"))
	if err != nil {
		return nil, fmt.Errorf("cannot read cadre-install-kernel SKILL.md: %w", err)
	}
	for _, relative := range lifecycleInstallSkillTargets {
		target := filepath.Join(pluginRoot, filepath.FromSlash(relative))
		if err := writeFile(target, string(installSkill)); err != nil {
			return nil, err
		}
		written = append(written, target)
	}

	for _, relative := range lifecycleBinTargets {
		target := filepath.Join(pluginRoot, filepath.FromSlash(relative))
		body := installKernelShim
		if filepath.Base(target) == "agentic-sdlc" {
			body = agenticSDLCShim
		}
		if err := writeFile(target, body); err != nil {
			return nil, err
		}
		// Useless without the executable bit: Claude Code adds bin/ to PATH but
		// does not chmod anything.
		if err := os.Chmod(target, 0o755); err != nil { //nolint:gosec // intentionally executable
			return nil, err
		}
		written = append(written, target)
	}
	return written, nil
}

// lifecycleHooks is the SessionStart detect-and-report hook. It runs before the
// human has asked for anything, on every session start, so it must not
