// generateKernelCompatibility ships the kernel compatibility window, the
// bootstrap script, the SessionStart hook, the install skill, and the two bin
// shims into each lifecycle plugin.
//
// The window is derived from provider.json rather than copied wholesale: the
// bootstrap only needs {minimum, maximum_exclusive}, and provider.json also
// carries an unrelated `version` field that has been mistaken for the kernel
// range before.
func (g *pluginGenerator) generateKernelCompatibility(pluginRoot string) ([]string, error) {
	manifest, err := g.providerManifest()
	if err != nil {
		return nil, err
	}
	compatibilityAny, ok := manifest.Get("kernel_compatibility")
	if !ok {
		return nil, fmt.Errorf("provider.json: missing kernel_compatibility")
	}
	compatibility, ok := compatibilityAny.(*orderedJSON)
	if !ok {
		return nil, fmt.Errorf("provider.json: kernel_compatibility is not an object")
	}
	minimum, _ := compatibility.Get("minimum")
	maximum, _ := compatibility.Get("maximum_exclusive")
	payload := newOrderedJSON().
		Set("_comment", "Generated from provider.json's kernel_compatibility by "+
			"cadre generate-plugin. Do not hand-edit; edit provider/provider.json "+
			"and regenerate.").
		Set("minimum", minimum).
		Set("maximum_exclusive", maximum)
	payloadText := pyJSONDumps(payload, 0) + "\n"

	var written []string
	for _, relative := range kernelCompatibilityTargets {
		target := filepath.Join(pluginRoot, filepath.FromSlash(relative))
		if err := writeFile(target, payloadText); err != nil {
			return nil, err
		}
		written = append(written, target)
	}

	hooksJSON := pyJSONDumps(lifecycleHooks(), 0) + "\n"
	for _, relative := range lifecycleHookTargets {
		target := filepath.Join(pluginRoot, filepath.FromSlash(relative))
		if err := writeFile(target, hooksJSON); err != nil {
			return nil, err
		}
		written = append(written, target)
	}

	kernelVersion, err := readKernelVersion(g.repoRoot)
	if err != nil {
		return nil, err
	}
	for _, relative := range lifecycleBinTargets {
		target := filepath.Join(pluginRoot, filepath.FromSlash(relative))
		if err := writeFile(target, agenticSDLCShim(kernelVersion)); err != nil {
			return nil, err
		}
		// Useless without the executable bit: Claude Code adds bin/ to PATH but
		// does not chmod anything.
		if err := os.Chmod(target, 0o755); err != nil { //nolint:gosec // intentionally executable
			return nil, err
		}
		written = append(written, target)
	}
	return written, nil
}

// lifecycleHooks is the SessionStart detect-and-report hook. It runs before the
// human has asked for anything, on every session start, so it must not
// install, must not write, and must not fail.
func lifecycleHooks() *orderedJSON {
	entry := newOrderedJSON().
		Set("type", "command").
		Set("command", `"${CLAUDE_PLUGIN_ROOT}/bin/cadre-install-kernel" --check`).
		// A hook that stalls degrades every session start for a problem that is
		// at worst "one optional feature is not set up yet".
		Set("timeout", 15)
	group := newOrderedJSON().Set("hooks", []any{entry})
	return newOrderedJSON().Set("hooks", newOrderedJSON().Set("SessionStart", []any{group}))
}

// mainPluginHooks wires the packaged destructive-git guard. The command line
// mirrors this repository's own .claude/settings.json exactly, substituting
// ${CLAUDE_PLUGIN_ROOT} for ${CLAUDE_PROJECT_DIR}.
func mainPluginHooks() *orderedJSON {
	entry := newOrderedJSON().
		Set("type", "command").
		Set("command", `"${CLAUDE_PLUGIN_ROOT}/`+guardHookTarget+`"`)
	matcher := newOrderedJSON().
		Set("matcher", "Bash").
		Set("hooks", []any{entry})
	return newOrderedJSON().Set("hooks", newOrderedJSON().Set("PreToolUse", []any{matcher}))
}

// generateMainPluginHook packages this repository's own destructive-git
// PreToolUse guard into the main `cadre` plugin, so any project that installs
// the plugin gets the same structural protection this repository runs on
// itself, without needing the separate cadre-lifecycle-* plugins.
func (g *pluginGenerator) generateMainPluginHook(pluginRoot string) ([]string, error) {
	written := []string{}

	// The selector, then every platform binary it can reach. Copied rather
	// than built: `generate-plugin --check` compares committed output against
	// a fresh run, and a rebuilt binary is only byte-identical when the Go
	// toolchain matches, which would make the drift guard fail for a reason
	// that has nothing to do with drift. The binaries are committed under
	// hooks/bin and refreshed by `make guard-binaries`;
	// TestTheCommittedGuardBinaryMatchesTheSource checks they are current by
	// running one, not by comparing bytes.
	guardTarget := filepath.Join(pluginRoot, filepath.FromSlash(guardHookTarget))
	if err := copyFile(filepath.Join(g.guardHookSource, "guard"), guardTarget); err != nil {
		return nil, err
	}
	written = append(written, guardTarget)

	binaries, err := os.ReadDir(filepath.Join(g.guardHookSource, "bin"))
	if err != nil {
		return nil, fmt.Errorf("the guard binaries are missing (%w) -- run `make guard-binaries`", err)
	}
	copied := 0
	for _, entry := range binaries {
		if entry.IsDir() || !strings.HasPrefix(entry.Name(), "cadre-guard-") {
			continue
		}
		target := filepath.Join(pluginRoot, filepath.FromSlash(guardBinaryDir), entry.Name())
		if err := copyFile(filepath.Join(g.guardHookSource, "bin", entry.Name()), target); err != nil {
			return nil, err
		}
		written = append(written, target)
		copied++
	}
	if copied == 0 {
		// A plugin whose hook resolves to nothing is a plugin with no guard,
		// and the guard fails open, so nothing downstream would report it.
		return nil, fmt.Errorf("no guard binaries found under %s -- run `make guard-binaries`",
			filepath.Join(g.guardHookSource, "bin"))
	}

	hooksTarget := filepath.Join(pluginRoot, "hooks", "hooks.json")
	if err := writeFile(hooksTarget, pyJSONDumps(mainPluginHooks(), 0)+"\n"); err != nil {
		return nil, err
	}
	return append(written, hooksTarget), nil
}

