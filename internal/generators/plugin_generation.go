// generateProviderCopy copies this repository's provider/ bundle into the
// package root. The bundle is register-owned: the package receives a verbatim
// copy so an installed plugin carries its own provider contracts, and
// filesEqual then fails the drift check if the package's copy ever diverges.
func (g *pluginGenerator) generateProviderCopy(pluginRoot string) ([]string, error) {
	// The generated members of provider/ are produced by
	// `cadre generate-role-metadata`, not here, so this generator can only copy
	// whatever the register last committed. Editing a role's AGENT.md and
	// running generate-plugin alone would refresh the package's Claude Code
	// wrappers (built live from the catalog) while silently packaging stale
	// Codex wrappers and a stale catalog export -- and a following --check,
	// which compares package against the same stale register content, would
	// call it current. Fail loudly instead.
	expected := map[string]string{"agent-catalog.json": g.agentCatalogExportContent()}
	codexWrappers, err := g.codexWrapperContents()
	if err != nil {
		return nil, err
	}
	for name, body := range codexWrappers {
		expected["codex-agents/"+name] = body
	}
	var stale []string
	for relative, want := range expected {
		actual, err := os.ReadFile(filepath.Join(g.providerRoot, filepath.FromSlash(relative)))
		if err != nil || string(actual) != want {
			stale = append(stale, filepath.Join(g.providerRoot, filepath.FromSlash(relative)))
		}
	}
	if len(stale) > 0 {
		sort.Strings(stale)
		shown := stale
		suffix := ""
		if len(shown) > 5 {
			shown = shown[:5]
			suffix = " ..."
		}
		return nil, fmt.Errorf(
			"provider/ is stale; run `cadre generate-role-metadata` before regenerating the package: %s%s",
			strings.Join(shown, ", "), suffix)
	}

	var written []string
	for _, name := range providerBundle {
		source := filepath.Join(g.providerRoot, name)
		info, err := os.Lstat(source)
		if err != nil {
			return nil, fmt.Errorf(
				"%s: missing from the provider bundle; run `cadre generate-role-metadata` if it is generated content",
				source)
		}
		target := filepath.Join(pluginRoot, name)
		switch {
		case info.IsDir():
			// Dereferencing a symlink would silently vendor out-of-tree content
			// into a published package; refuse instead.
			copied, err := copyTree(source, target)
			if err != nil {
				return nil, err
			}
			written = append(written, copied...)
		case name == "agent-catalog.json":
			// Re-point `definition` from the register's provider/roles/ tree to
			// the package's own suite/roster/ copy of the same files. The kernel
			// resolves these relative to whichever copy it reads and rejects
			// escapes, so the two trees genuinely need different spellings.
			rewritten, err := rewriteAgentCatalog(source)
			if err != nil {
				return nil, err
			}
			if err := writeFile(target, rewritten); err != nil {
				return nil, err
			}
			written = append(written, target)
		default:
			if err := copyFile(source, target); err != nil {
				return nil, err
			}
			written = append(written, target)
		}
	}
	return written, nil
}

// rewriteAgentCatalog reads the register's agent-catalog.json and re-points
// each `definition` at the package's suite/roster/ copy, re-serialized with
// Python's json.dumps(indent=2) formatting.
func rewriteAgentCatalog(source string) (string, error) {
	raw, err := os.ReadFile(source)
	if err != nil {
		return "", err
	}
	parsed, err := parseOrderedJSON(raw)
	if err != nil {
		return "", fmt.Errorf("%s: %w", source, err)
	}
	agentsAny, ok := parsed.Get("agents")
	if !ok {
		return "", fmt.Errorf("%s: missing 'agents'", source)
	}
	agents, ok := agentsAny.(*orderedJSON)
	if !ok {
		return "", fmt.Errorf("%s: 'agents' is not an object", source)
	}
	for _, agentID := range agents.Keys() {
		entryAny, _ := agents.Get(agentID)
		entry, ok := entryAny.(*orderedJSON)
		if !ok {
			return "", fmt.Errorf("%s: agent %q is not an object", source, agentID)
		}
		definitionAny, _ := entry.Get("definition")
		definition, _ := definitionAny.(string)
		if !strings.HasPrefix(definition, providerDefinitionPrefix) {
			return "", fmt.Errorf(
				"%s: definition %q does not start with %q; run `cadre generate-role-metadata`",
				source, definition, providerDefinitionPrefix)
		}
		entry.Set("definition", packageDefinitionPrefix+definition[len(providerDefinitionPrefix):])
	}
	return pyJSONDumps(parsed, 0) + "\n", nil
}

