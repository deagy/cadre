func (g *pluginGenerator) generatePackage(pluginRoot string, writeReadme bool) ([]string, error) {
	if err := resetGeneratedContent(pluginRoot, writeReadme); err != nil {
		return nil, err
	}
	var written []string
	skills, err := g.generateSkillCopies(pluginRoot)
	if err != nil {
		return nil, err
	}
	written = append(written, skills...)

	suite, err := g.generateSuiteCopy(pluginRoot, writeReadme)
	if err != nil {
		return nil, err
	}
	written = append(written, suite...)

	agents, err := g.generateAgentWrappers(pluginRoot)
	if err != nil {
		return nil, err
	}
	written = append(written, agents...)

	provider, err := g.generateProviderCopy(pluginRoot)
	if err != nil {
		return nil, err
	}
	written = append(written, provider...)

	kernel, err := g.generateKernelCompatibility(pluginRoot)
	if err != nil {
		return nil, err
	}
	written = append(written, kernel...)

	hook, err := g.generateMainPluginHook(pluginRoot)
	if err != nil {
		return nil, err
	}
	written = append(written, hook...)

	launcher, err := g.generateBinWrapper(pluginRoot)
	if err != nil {
		return nil, err
	}
	written = append(written, launcher)
	return written, nil
}

// generatedFileSet enumerates the files under root that this generator owns.
func generatedFileSet(root string, compareReadme bool) (map[string]bool, error) {
	out := map[string]bool{}
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) {
				return nil
			}
			return err
		}
		if d.IsDir() {
			return nil
		}
		rel, relErr := filepath.Rel(root, p)
		if relErr != nil {
			return relErr
		}
		rel = filepath.ToSlash(rel)
		parts := strings.Split(rel, "/")
		owned := generatedTopLevel[parts[0]]
		if !owned {
			for _, nested := range generatedNestedPaths {
				if rel == nested || strings.HasPrefix(rel, nested+"/") {
					owned = true
					break
				}
			}
		}
		if !owned {
			return nil
		}
		for _, part := range parts {
			if part == "__pycache__" {
				return nil
			}
		}
		if ext := path.Ext(rel); ext == ".pyc" || ext == ".pyo" {
			return nil
		}
		if !compareReadme && rel == "README.md" {
			return nil
		}
		out[rel] = true
		return nil
	})
	if err != nil {
		return nil, err
	}
	return out, nil
}

func filesEqual(left, right string, compareReadme bool) (bool, []string, error) {
	leftFiles, err := generatedFileSet(left, compareReadme)
	if err != nil {
		return false, nil, err
	}
	rightFiles, err := generatedFileSet(right, compareReadme)
	if err != nil {
		return false, nil, err
	}
	var differences []string
	for rel := range leftFiles {
		if !rightFiles[rel] {
			differences = append(differences, "missing from target: "+rel)
		}
	}
	for rel := range rightFiles {
		if !leftFiles[rel] {
			differences = append(differences, "unexpected in target: "+rel)
		}
	}
	if len(differences) > 0 {
		sort.Strings(differences)
		return false, differences, nil
	}
	for rel := range leftFiles {
		leftBytes, err := os.ReadFile(filepath.Join(left, filepath.FromSlash(rel)))
		if err != nil {
			return false, nil, err
		}
		rightBytes, err := os.ReadFile(filepath.Join(right, filepath.FromSlash(rel)))
		if err != nil {
			return false, nil, err
		}
		if string(leftBytes) != string(rightBytes) {
			differences = append(differences, "content differs: "+rel)
		}
	}
	sort.Strings(differences)
	return len(differences) == 0, differences, nil
}

// PluginResult reports one generate-plugin run.
type PluginResult struct {
	OutputRoot  string
	Written     []string
	WroteReadme bool
	// Differences is populated in check mode and empty when the package is
	// current.
	Differences []string
	Current     bool
}

// GeneratePluginOptions carries the flags `cadre generate-plugin` accepts.
type GeneratePluginOptions struct {
	Check bool
	// ForceReadme writes the register's own README.md over an existing
	// downstream package's README.md.
	ForceReadme bool
}

// RunGeneratePlugin is the `cadre generate-plugin` implementation. It mirrors
// generate_global_plugin.py's main().
func RunGeneratePlugin(repoRoot, outputRoot string, options GeneratePluginOptions) (*PluginResult, error) {
	absOutput, err := filepath.Abs(filepath.FromSlash(outputRoot))
	if err != nil {
		return nil, fmt.Errorf("cannot resolve output root: %w", err)
	}

	// An existing .codex-plugin/plugin.json at the target means it is already
	// an initialized, hand-authored downstream package -- not a fresh
	// distribution target -- so its own README.md is downstream-owned and must
	// survive regeneration untouched.
	markerInfo, markerErr := os.Stat(filepath.Join(absOutput, ".codex-plugin", "plugin.json"))
	preexistingMarker := markerErr == nil && !markerInfo.IsDir()
	writeReadme := options.ForceReadme || !preexistingMarker

	if !options.Check {
		if entries, err := os.ReadDir(absOutput); err == nil {
			if len(entries) > 0 && !preexistingMarker {
				return nil, errors.New("--output must be a new directory or an existing generated plugin")
			}
		} else if !os.IsNotExist(err) {
			return nil, fmt.Errorf("cannot read output directory: %w", err)
		}
	}

	generator, err := newPluginGenerator(repoRoot)
	if err != nil {
		return nil, err
	}

	if options.Check {
		temporary, err := os.MkdirTemp("", "cadre-plugin-")
		if err != nil {
			return nil, err
		}
		defer os.RemoveAll(temporary) //nolint:errcheck // best-effort cleanup
		candidate := filepath.Join(temporary, "cadre")
		if _, err := generator.generatePackage(candidate, true); err != nil {
			return nil, err
		}
		if _, err := os.Stat(absOutput); err != nil {
			return &PluginResult{
				OutputRoot:  absOutput,
				Current:     false,
				Differences: []string{"output directory does not exist: " + absOutput},
			}, nil
		}
		current, differences, err := filesEqual(candidate, absOutput, writeReadme)
		if err != nil {
			return nil, err
		}
		result := &PluginResult{OutputRoot: absOutput, Current: current, Differences: differences}
		if !current {
			return result, nil
		}
		if err := validateProviderBundle(repoRoot); err != nil {
			return nil, err
		}
		return result, nil
	}

	written, err := generator.generatePackage(absOutput, writeReadme)
	if err != nil {
		return nil, err
	}
	return &PluginResult{
		OutputRoot:  absOutput,
		Written:     written,
		WroteReadme: writeReadme,
		Current:     true,
	}, nil
}

// validateProviderBundle asks the lifecycle kernel to validate the provider
// bundle, when one is resolvable. Silently skipped otherwise -- the kernel is
// an optional, separately versioned dependency.
func validateProviderBundle(repoRoot string) error {
	kernel := os.Getenv("AGENTIC_SDLC_BIN")
	if kernel == "" {
		resolved, err := exec.LookPath("agentic-sdlc")
		if err != nil {
			return nil
		}
		kernel = resolved
	}
	command := exec.Command(kernel, "--provider",
		filepath.Join(repoRoot, "provider", "provider.json"), "provider", "list")
	command.Dir = repoRoot
	output, err := command.CombinedOutput()
	if err != nil {
		return fmt.Errorf("provider validation failed: %s", strings.TrimSpace(string(output)))
	}
	return nil
}

