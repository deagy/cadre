type roleWrapperInputs struct {
	definition      string
	description     string
	profile         capabilityProfile
	model           string
	codexModel      string
	reasoningEffort string
	instructions    string
}

// roleWrapperInputs is the wrapper content both runners derive from one role.
// generateAgentWrappers (Claude Code, package-only) and codexWrapperContents
// (Codex, register-side under provider/) write to different trees but must
// embed byte-identical role and shared-policy instructions.
func (g *pluginGenerator) roleWrapperInputs(agentID string) (*roleWrapperInputs, error) {
	metadata := g.meta(agentID)
	definition := metadata["definition"]
	phase := metadata["phase"]
	if phase == "" {
		phase = "unknown"
	}
	capability := metadata["capability"]
	profile := g.capabilities.CapabilityTiers[capability]

	loadPolicySections := func(relatives []string) ([]string, error) {
		// Shared policy files are optional: a project (or this repository) may
		// not have every one of them, or may have emptied one, and neither
		// state is a defect. Skip missing or emptied files rather than failing,
		// and don't leave a stray blank section behind.
		var sections []string
		for _, relative := range relatives {
			raw, err := os.ReadFile(filepath.Join(g.repoRoot, filepath.FromSlash(relative)))
			if err != nil {
				continue
			}
			body := strings.TrimSpace(string(raw))
			if body == "" {
				continue
			}
			if _, universal := universalPolicySections[relative]; universal && !g.writeCapable[capability] {
				excerpt, err := excerptUniversalSections(relative, body)
				if err != nil {
					return nil, err
				}
				body = excerpt
			}
			sections = append(sections, fmt.Sprintf("# Shared policy: %s\n\n%s", relative, body))
		}
		return sections, nil
	}

	sharedSections, err := loadPolicySections(sharedPolicies)
	if err != nil {
		return nil, err
	}
	// TIER_SCOPED_POLICIES is currently empty upstream; the mechanism is kept
	// there because the tier-gating question recurs. Nothing to append here.
	sharedContent := strings.Join(sharedSections, "\n\n")

	// A migrated role's AGENT.md carries `---`-delimited frontmatter ahead of
	// its prose body; that frontmatter is generated-file bookkeeping for
	// catalog.yaml/routing.json, not role instructions, so it must never be
	// embedded into the wrapper.
	rawRole, err := os.ReadFile(filepath.Join(g.rosterRoot, filepath.FromSlash(definition)))
	if err != nil {
		return nil, fmt.Errorf("cannot read role definition %s: %w", definition, err)
	}
	stripped, err := StripFrontmatter(string(rawRole))
	if err != nil {
		return nil, fmt.Errorf("%s: %w", definition, err)
	}
	roleBody := strings.TrimSpace(stripped)

	parts := []string{fmt.Sprintf("# Role: %s\n\n%s", agentID, roleBody)}
	if sharedContent != "" {
		parts = append(parts, sharedContent)
	}
	parts = append(parts, sharedOverrideNote, askHumanRule)

	return &roleWrapperInputs{
		definition:      definition,
		description:     fmt.Sprintf("Secure cloud agent suite role for the %s phase (%s).", phase, agentID),
		profile:         profile,
		model:           metadata["model"],
		codexModel:      metadata["codex_model"],
		reasoningEffort: metadata["reasoning_effort"],
		instructions:    strings.Join(parts, "\n\n"),
	}, nil
}

// generateAgentWrappers writes the Claude Code plugin-bundled subagent
// wrappers. Package-only: Claude Code auto-discovers these from the installed
// plugin's agents/ directory, so they have no meaning outside it.
func (g *pluginGenerator) generateAgentWrappers(pluginRoot string) ([]string, error) {
	var written []string
	for _, agentID := range g.catalogIDs {
		inputs, err := g.roleWrapperInputs(agentID)
		if err != nil {
			return nil, err
		}
		lines := []string{
			"---",
			"name: " + agentID,
			"description: " + inputs.description,
			"tools: " + strings.Join(inputs.profile.Tools, ", "),
		}
		if inputs.model != "" {
			lines = append(lines, "model: "+inputs.model)
		}
		if inputs.reasoningEffort != "" {
			lines = append(lines, "effort: "+inputs.reasoningEffort)
		}
		lines = append(lines,
			"generated: true",
			"canonical_source: roster/"+inputs.definition,
			"---",
			"",
			inputs.instructions,
			"",
		)
		target := filepath.Join(pluginRoot, "agents", agentID+".md")
		if err := writeFile(target, strings.Join(lines, "\n")); err != nil {
			return nil, err
		}
		written = append(written, target)
	}
	return written, nil
}

// codexWrapperContents renders the Codex role wrappers as {filename: content},
// for provider/codex-agents/. Codex discovers custom agents only from
// ~/.codex/agents/ or a project's .codex/agents/, never from a plugin
// manifest, so these are a tracked staging copy that `cadre bootstrap-codex`
// installs from. This generator only needs them to detect a stale provider/.
func (g *pluginGenerator) codexWrapperContents() (map[string]string, error) {
	contents := map[string]string{}
	for _, agentID := range g.catalogIDs {
		inputs, err := g.roleWrapperInputs(agentID)
		if err != nil {
			return nil, err
		}
		// `model` uses catalog.yaml's separate `codex_model` OpenAI identifier,
		// not the Claude Code wrapper's haiku/sonnet/opus tier name -- the two
		// runners don't share a model-naming space.
		codexAgentID := "agents-" + agentID
		lines := []string{
			"# GENERATED FILE: canonical source is roster/" + inputs.definition,
			"name = " + pyJSONString(codexAgentID),
			"description = " + pyJSONString(inputs.description),
			"sandbox_mode = " + pyJSONString(inputs.profile.SandboxMode),
		}
		if inputs.codexModel != "" {
			lines = append(lines, "model = "+pyJSONString(inputs.codexModel))
		}
		if inputs.reasoningEffort != "" {
			lines = append(lines, "model_reasoning_effort = "+pyJSONString(inputs.reasoningEffort))
		}
		lines = append(lines,
			"developer_instructions = "+pyJSONString(inputs.instructions),
			"",
		)
		contents[codexAgentID+".toml"] = strings.Join(lines, "\n")
	}
	return contents, nil
}

func deriveKind(definition string) string {
	if strings.HasPrefix(definition, "review/") || definition == "engineering/test-engineer/AGENT.md" {
		return "reviewer"
	}
	if strings.HasPrefix(definition, "support/") {
		return "specialist"
	}
	if definition == "documentation/evidence-curator/AGENT.md" || definition == "knowledge-store/AGENT.md" {
		return "specialist"
	}
	return "author"
}

// agentCatalogExportContent renders the package-relative catalog export
// consumed through provider.json. Written into this repository's own provider/
// bundle by `cadre generate-role-metadata`; reproduced here only to detect a
// stale provider/ before packaging it.
func (g *pluginGenerator) agentCatalogExportContent() string {
	agents := newOrderedJSON()
	for _, agentID := range g.catalogIDs {
		metadata := g.meta(agentID)
		phase := metadata["phase"]
		if phase == "" {
			phase = "unknown"
		}
		kind := deriveKind(metadata["definition"])
		capabilities := []string{"author", "dispatch"}
		if kind == "reviewer" {
			capabilities = []string{"reviewer"}
		}
		agents.Set(agentID, newOrderedJSON().
			Set("phase", phase).
			Set("kind", kind).
			Set("capabilities", capabilities).
			Set("definition", providerDefinitionPrefix+metadata["definition"]))
	}
	root := newOrderedJSON().Set("schema_version", 1).Set("agents", agents)
	return pyJSONDumps(root, 0) + "\n"
}

