func (g *pluginGenerator) generateSuiteCopy(pluginRoot string, writeReadme bool) ([]string, error) {
	trackedList, err := gitTrackedFiles(g.repoRoot, "roster")
	if err != nil {
		return nil, err
	}
	tracked := map[string]bool{}
	for _, relative := range trackedList {
		// The packaged suite carries no Python. The wrapper used to exec
		// roster/**/*.py whenever it could not resolve the Go binary, and
		// that fallback is what made these ~24,500 lines part of the
		// distribution. It is gone -- the wrapper now fails with a
		// diagnostic instead -- so the scripts it pointed at are dead weight
		// a consumer would still have to trust and audit.
		//
		// Data is unaffected: role definitions, catalog.yaml, routing.json
		// and the context packs are what the binary actually reads.
		if strings.HasSuffix(relative, ".py") {
			continue
		}
		tracked[relative] = true
	}
	for _, helper := range []string{} {
		if info, err := os.Stat(filepath.Join(g.repoRoot, filepath.FromSlash(helper))); err == nil && !info.IsDir() {
			tracked[helper] = true
		}
	}

	// `catalog` was parsed straight off the worktree copy of catalog.yaml, but
	// `tracked` only reflects git's index -- an uncommitted new role's AGENT.md
	// would otherwise pass silently, then still get a wrapper and an
	// agent-catalog.json entry, producing a package that references a suite
	// file that was never copied. Fail loudly here instead.
	var untrackedRolePaths []string
	for _, agentID := range g.catalogIDs {
		relative := "roster/" + g.meta(agentID)["definition"]
		if !tracked[relative] {
			untrackedRolePaths = append(untrackedRolePaths, relative)
		}
	}
	if len(untrackedRolePaths) > 0 {
		sort.Strings(untrackedRolePaths)
		return nil, fmt.Errorf(
			"roster/catalog.yaml references role definition file(s) not tracked in git; "+
				"commit them (git add) before regenerating the plugin: %s",
			strings.Join(untrackedRolePaths, ", "))
	}

	// The guard that used to sit here required every script named in
	// bin/subcommands.tsv to be tracked and copied into suite/, because the
	// wrapper emitted a case arm exec'ing each one -- an untracked script
	// produced a wrapper pointing at a file the package did not contain.
	//
	// Both halves of that are gone: the table has no script column, and the
	// wrapper execs the Go binary rather than per-subcommand scripts. There
	// is nothing left for it to check.

	rolePaths := map[string]bool{}
	for _, agentID := range g.catalogIDs {
		rolePaths["roster/"+g.meta(agentID)["definition"]] = true
	}

	documentationPaths := map[string]bool{
		"AGENTS.md":       true,
		"CONTRIBUTING.md": true,
		"IDENTITY.md":     true,
	}
	docsRoot := filepath.Join(g.repoRoot, "docs")
	if err := filepath.WalkDir(docsRoot, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			if os.IsNotExist(err) {
				return nil
			}
			return err
		}
		if d.IsDir() {
			return nil
		}
		rel, relErr := filepath.Rel(g.repoRoot, p)
		if relErr != nil {
			return relErr
		}
		rel = filepath.ToSlash(rel)
		if !isKernelDoc(rel) {
			documentationPaths[rel] = true
		}
		return nil
	}); err != nil && !os.IsNotExist(err) {
		return nil, err
	}

	trackedSorted := make([]string, 0, len(tracked))
	for relative := range tracked {
		trackedSorted = append(trackedSorted, relative)
	}
	sort.Strings(trackedSorted)

	var selected []string
	selectedSet := map[string]bool{}
	add := func(relative string) {
		selected = append(selected, relative)
		selectedSet[relative] = true
	}
	for _, relative := range trackedSorted {
		switch {
		case documentationPaths[relative]:
			add(relative)
		case rolePaths[relative] || suiteRosterRootAllowlist[relative]:
			add(relative)
		case strings.HasPrefix(relative, "roster/context-packs/"):
			add(relative)
		case strings.HasPrefix(relative, "roster/shared/"), strings.HasPrefix(relative, "roster/workflows/"):
			add(relative)
		case strings.HasPrefix(relative, "roster/orchestration/") &&
			!strings.Contains(relative, "/runs/") &&
			!strings.Contains(relative, "/test/") &&
			!strings.Contains(relative, "/examples/") &&
			!strings.HasSuffix(relative, "generate_global_plugin.py") &&
			!strings.HasSuffix(relative, "migrate_execution_summary.py") &&
			!strings.HasSuffix(relative, "plugin_version.py") &&
			// These two scripts import generate_global_plugin.py (excluded
			// above) and their subcommands are already excluded from the
			// packaged bin/cadre wrapper -- packaging them anyway would ship a
			// non-functional entry point that looks runnable but isn't.
			!strings.HasSuffix(relative, "generate_role_metadata.py") &&
			!strings.HasSuffix(relative, "generate_authority_aides.py"):
			add(relative)
		case strings.HasPrefix(relative, "roster/knowledge-store/src/") || knowledgeStoreExtras[relative]:
			add(relative)
		case contextStoreExtras[relative]:
			// The context store's documentation travels with the distribution;
			// its implementation no longer does. roster/context-store/src/ was
			// deleted once `cadre context` was served entirely by the Go
			// binary -- and the packaged bin/cadre execs that binary for every
			// subcommand, with no Python path at all, so the modules were
			// dead weight rather than the "CLI cannot import its own code"
			// hazard this branch was written to avoid.
			add(relative)
		}
	}

	docsSorted := make([]string, 0, len(documentationPaths))
	for relative := range documentationPaths {
		docsSorted = append(docsSorted, relative)
	}
	sort.Strings(docsSorted)
	for _, relative := range docsSorted {
		if selectedSet[relative] {
			continue
		}
		if info, err := os.Stat(filepath.Join(g.repoRoot, filepath.FromSlash(relative))); err != nil || info.IsDir() {
			continue
		}
		add(relative)
	}

	var written []string
	// The packaged README is register-owned (packaging/plugin-README.md) and
	// rendered to two places: the package root, where it is the repository's
	// front page, and suite/README.md, where the packaged docs cross-reference
	// it. The package-root copy is skipped when writeReadme is false: a target
	// that already has its own .codex-plugin/plugin.json is itself a
	// hand-authored downstream package, not a fresh distribution target, and
	// keeps its own README.md untouched.
	readmeRaw, err := os.ReadFile(g.packagingReadme)
	if err != nil {
		return nil, fmt.Errorf("cannot read %s: %w", g.packagingReadme, err)
	}
	packageReadme := string(readmeRaw)
	if writeReadme {
		target := filepath.Join(pluginRoot, "README.md")
		if err := writeFile(target, packageReadme); err != nil {
			return nil, err
		}
		written = append(written, target)
	}
	suiteReadme := filepath.Join(pluginRoot, "suite", "README.md")
	if err := writeFile(suiteReadme, generatedMarker+"\n\n"+packageReadme); err != nil {
		return nil, err
	}
	written = append(written, suiteReadme)

	for _, relative := range selected {
		source := filepath.Join(g.repoRoot, filepath.FromSlash(relative))
		target := filepath.Join(pluginRoot, "suite", filepath.FromSlash(relative))
		if strings.ToLower(filepath.Ext(target)) != ".md" {
			if err := copyFile(source, target); err != nil {
				return nil, err
			}
			written = append(written, target)
			continue
		}
		raw, err := os.ReadFile(source)
		if err != nil {
			return nil, err
		}
		content, err := rewritePackagedMarkdown(string(raw), relative, pluginRoot, filepath.Dir(target))
		if err != nil {
			return nil, fmt.Errorf("%s: %w", relative, err)
		}
		if err := writeFile(target, content); err != nil {
			return nil, err
		}
		written = append(written, target)
	}
	return written, nil
}

// rewritePackagedMarkdown applies every link rewrite the packaged copy of a
// Markdown source needs, then stamps the generated-file marker. Order matters
// and mirrors the Python exactly.
func rewritePackagedMarkdown(content, relative, pluginRoot, targetParent string) (string, error) {
	content = strings.ReplaceAll(content, "../bin/cadre", "../../bin/cadre")

	// Links to the register's top-level README point at the packaged README
	// under suite/. Depth-aware: a plain "../README.md" -> "README.md"
	// substring replace also matches inside "../../README.md" (written by files
	// one level deeper), silently retargeting them to suite/roster/README.md --
	// a file that exists, so no link checker catches it.
	sourceDepth := len(strings.Split(relative, "/")) - 1
	if sourceDepth > 0 {
		rootReadme := strings.Repeat("../", sourceDepth) + "README.md"
		suiteReadme, err := relSlash(targetParent, filepath.Join(pluginRoot, "suite", "README.md"))
		if err != nil {
			return "", err
		}
		content = strings.ReplaceAll(content, rootReadme, suiteReadme)
	}

	// The register's source for the packaged README has no counterpart inside
	// the package; point at the packaged copy of it instead.
	content = strings.ReplaceAll(content, "../packaging/plugin-README.md", "../README.md")

	// Skills are packaged at the package root (skills/<name>/) by default, not
	// under suite/, so a source link into .agents/skills/ would dangle.
	// Computed per file rather than hardcoded, and skill-name-aware because
	// skillPackageTargets retargets some skills into a sub-plugin directory.
	toPackageRoot, err := relSlash(targetParent, pluginRoot)
	if err != nil {
		return "", err
	}
	for _, pattern := range skillLinkPatterns {
		content = pattern.ReplaceAllStringFunc(content, func(match string) string {
			groups := pattern.FindStringSubmatch(match)
			skillName := groups[1]
			packageSubdir := "skills"
			if override, ok := skillPackageTargets[skillName]; ok {
				packageSubdir = override
			}
			return toPackageRoot + "/" + packageSubdir + "/" + skillName
		})
	}

	// Not packaged at all (the package ships no changelog, and tests are
	// excluded), so point at the register instead of dangling.
	content = strings.ReplaceAll(content, "](../CHANGELOG.md)", "]("+registerURL+"/blob/main/CHANGELOG.md)")
	content = strings.ReplaceAll(content, "](../roster/orchestration/test/",
		"]("+registerURL+"/blob/main/roster/orchestration/test/")

	// A migrated role's AGENT.md starts with `---`-delimited frontmatter;
	// inserting the marker at byte 0 would land it inside that block instead of
	// before it, corrupting it. Insert after the closing delimiter instead.
	if IsMigrated(content) {
		end, ok, err := FrontmatterClosingDelimiterEnd(content)
		if err != nil {
			return "", err
		}
		if ok {
			return content[:end] + "\n\n" + generatedMarker + content[end:], nil
		}
	}
	return generatedMarker + "\n\n" + content, nil
}

